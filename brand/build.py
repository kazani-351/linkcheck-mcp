# Regenerates src/brand-assets.ts from the files in this folder.
# PNGs are rendered from og.html / icons.html in Safari (see brand/README.md).
# Run: python3 brand/build.py
import base64, json, pathlib
here = pathlib.Path(__file__).parent
out = ["// GENERATED by brand/build.py from brand/*. Do not edit by hand.", ""]
for name, const in [("logo.svg", "LOGO_SVG"), ("mark.svg", "MARK_SVG")]:
    out.append(f"export const {const} = {json.dumps((here / name).read_text().strip())};")
for name, const in [("og.png", "OG_PNG_B64"), ("apple-touch-icon.png", "APPLE_ICON_PNG_B64"), ("icon-256.png", "ICON_256_PNG_B64")]:
    out.append(f'export const {const} = "{base64.b64encode((here / name).read_bytes()).decode()}";')
(here.parent / "src" / "brand-assets.ts").write_text("\n".join(out) + "\n")
print("wrote src/brand-assets.ts")
